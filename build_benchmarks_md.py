"""Builds BENCHMARKS.md from a results.json produced by run_trial/auto_optimize.

Renders one section per model: best config first, then every trial. Columns
include prefill TPS, quality (skipped when reasoning exhausts the token
budget), VRAM estimate, and any judge notes.
"""

import argparse
import json
from collections import defaultdict


def fmt_quality(row):
    score = row.get("quality_score")
    if score is None:
        reasoning = (row.get("judge_reasoning") or "").lower()
        if "reasoning consumed" in reasoning:
            return "—"  # judge intentionally skipped
        return "N/A"
    return f"{score}/10"


def fmt_vram(row):
    peak = row.get("peak_vram_gb")
    if peak is not None:
        return f"{peak}"
    est = row.get("vram_estimate_gb")
    return f"~{est} (est)" if est is not None else "N/A"


def render(results, header_note: str = "") -> str:
    by_model = defaultdict(list)
    for row in results:
        by_model[row.get("model", "Unknown")].append(row)

    lines = [
        "# LM Studio Benchmark Results",
        "",
        ("Generated by `auto_optimize.py --judge` against a real LM Studio "
         "instance. Each model's best context is the highest TPS among "
         "configurations that loaded successfully (ties broken toward larger "
         "context)."),
        "",
    ]
    if header_note:
        lines += [header_note, ""]

    for model in sorted(by_model):
        rows = by_model[model]
        successes = [r for r in rows if r.get("status") == "Success"]
        lines += [f"## `{model}`", ""]
        if not successes:
            lines += [
                "_No configuration loaded successfully on this hardware._",
                "",
                "| Context | Status | Notes |",
                "|---|---|---|",
            ]
            for r in sorted(rows, key=lambda x: x.get("context_length", 0)):
                err = (r.get("error") or "").strip()[:120]
                lines.append(
                    f"| {r.get('context_length', '—')} "
                    f"| {r.get('status', '—')} "
                    f"| {err or 'see LM Studio main.log for size estimate'} |"
                )
            lines.append("")
            continue
        best = max(
            successes,
            key=lambda r: (r.get("tps", 0.0), r.get("context_length", 0)),
        )
        best_prefill = best.get("prefill_tps")
        prefill_text = (
            f"{best_prefill:.1f}" if best_prefill is not None else "N/A"
        )
        lines += [
            f"- **Best:** context **{best['context_length']}**, "
            f"**{best['tps']:.2f} TPS** "
            f"(prefill {prefill_text} TPS, TTFT {best['ttft']:.2f}s)",
            f"- **VRAM estimate (load):** {fmt_vram(best)}",
            "",
            "| Context | Status | TTFT (s) | Prefill TPS | TPS | Quality | "
            "VRAM | Notes |",
            "|---|---|---|---|---|---|---|---|",
        ]
        rows_sorted = sorted(rows, key=lambda r: r.get("context_length", 0))
        for r in rows_sorted:
            ctx = r.get("context_length", "—")
            status = r.get("status", "—")
            ttft = f"{r.get('ttft', 0):.2f}"
            prefill_val = r.get("prefill_tps")
            prefill = f"{prefill_val:.1f}" if prefill_val is not None else "N/A"
            tps = f"**{r.get('tps', 0):.2f}**"
            quality = fmt_quality(r)
            vram = fmt_vram(r)
            note = ""
            jr = r.get("judge_reasoning") or ""
            if "reasoning consumed" in jr.lower():
                note = "reasoning consumed budget"
            elif status == "OOM/Load Fail":
                note = "did not load"
            lines.append(
                f"| {ctx} | {status} | {ttft} | {prefill} | {tps} | "
                f"{quality} | {vram} | {note} |"
            )
        lines.append("")

    lines += [
        "## How to reproduce",
        "",
        "```bash",
        "./.venv/bin/python auto_optimize.py \\",
        "    --model <MODEL_KEY> --judge --results results.json",
        "./.venv/bin/python generate_report.py \\",
        "    --input results.json --output leaderboard.md",
        "```",
        "",
        ("`auto_optimize.py` searches the highest loadable GPU offload ratio "
         "(SDK transport only) and the largest context up to `--max_context` "
         "(default 16384). With `--judge`, each trial's output is scored 1-10 "
         "by an LLM-as-a-judge; when a reasoning model spends the whole token "
         "budget thinking (empty visible output), the judge step is skipped "
         "rather than recording a misleading 1/10."),
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", default="results.json")
    parser.add_argument("--output", default="BENCHMARKS.md")
    parser.add_argument("--header-note", default="")
    args = parser.parse_args()

    with open(args.input) as f:
        results = json.load(f)
    text = render(results, args.header_note)
    with open(args.output, "w") as f:
        f.write(text)
    print(f"Wrote {args.output}: {len(results)} trial rows.")


if __name__ == "__main__":
    main()
